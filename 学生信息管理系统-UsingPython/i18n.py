def set_language(code):
    """切换当前界面语言（zh_cn / zh_tw / en / ru）。"""
    global _lang
    if code in LANGS:
        _lang = code


def get_language():
    """返回当前语言代码。"""
    return _lang


def get_language_name(code=None):
    """返回语言代码对应的显示名称。"""
    return LANGS.get(code or _lang, LANGS["zh_cn"])


def tr(text):
    """按当前语言翻译文本；无译文时回退为原文。"""
    if not text:
        return text
    table = {
        "zh_tw": _ZH_TW,
        "en": _EN,
        "ru": _RU,
    }.get(_lang)
    if table is None:
        return text
    return table.get(text, text)
